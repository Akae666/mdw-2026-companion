const storeKey = "mdw2026-personal-companion";
const defaultState = { checked: {}, missed: {}, reflections: [], photos: [] };
let state = loadState();

function $(selector) {
  return document.querySelector(selector);
}

function loadState() {
  try {
    return { ...defaultState, ...JSON.parse(localStorage.getItem(storeKey)) };
  } catch {
    return { ...defaultState };
  }
}

function saveState() {
  localStorage.setItem(storeKey, JSON.stringify(state));
  renderStats();
}

function programById(id) {
  return programs.find((item) => item[0] === id);
}

function eventName(id) {
  return programById(id)?.[1] || id;
}

function pageName() {
  return document.body.dataset.page;
}

function getParam(name) {
  return new URLSearchParams(location.search).get(name);
}

function detailUrl(id) {
  return `program-detail.html?id=${encodeURIComponent(id)}`;
}

function renderStats() {
  const checked = Object.values(state.checked).filter(Boolean).length;
  const missed = Object.values(state.missed || {}).filter(Boolean).length;
  const reflections = state.reflections.length;
  const photos = state.photos.length;
  if ($("#stat-checked")) $("#stat-checked").textContent = checked;
  if ($("#stat-missed")) $("#stat-missed").textContent = missed;
  if ($("#stat-reflections")) $("#stat-reflections").textContent = reflections;
  if ($("#stat-photos")) $("#stat-photos").textContent = photos;
}

function setActiveNav() {
  const current = pageName() === "program-detail" ? "program" : pageName();
  document.querySelectorAll(".top-nav a").forEach((link) => {
    link.classList.toggle("active", link.getAttribute("href")?.includes(`${current}.html`));
  });
}

