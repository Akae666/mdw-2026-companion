function addReflection(event) {
  event.preventDefault();
  const programId = event.currentTarget.dataset.programId;
  if (!programId) return;
  const editId = $("#detail-edit-id").value;
  const payload = {
    memory: $("#detail-memory").value.trim(),
    material: $("#detail-material").value.trim(),
    note: $("#detail-note").value.trim()
  };
  if (editId) {
    const existing = state.reflections.find((item) => item.id === editId);
    if (existing) Object.assign(existing, payload, { updatedAt: new Date().toISOString() });
  } else {
    state.reflections.push({
      id: crypto.randomUUID(),
      eventId: programId,
      ...payload,
      createdAt: new Date().toISOString()
    });
  }
  state.checked[programId] = true;
  state.missed[programId] = false;
  saveState();
  closeThoughtForm();
  renderDetail();
}

function openThoughtForm(reflectionId = "") {
  const form = $("#detail-reflection-form");
  if (!form) return;
  form.hidden = false;
  $("#detail-edit-id").value = reflectionId;
  const existing = state.reflections.find((item) => item.id === reflectionId);
  $("#detail-memory").value = existing?.memory || "";
  $("#detail-material").value = existing?.material || "";
  $("#detail-note").value = existing?.note || "";
  $("#detail-save-thought").textContent = reflectionId ? "更新这条记录" : "保存这条记录";
  $("#detail-memory").focus();
}

function closeThoughtForm() {
  const form = $("#detail-reflection-form");
  if (!form) return;
  form.reset();
  $("#detail-edit-id").value = "";
  form.hidden = true;
}

function resizeImage(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = reject;
    reader.onload = () => {
      const image = new Image();
      image.onerror = reject;
      image.onload = () => {
        const maxSide = 1600;
        const scale = Math.min(1, maxSide / Math.max(image.width, image.height));
        const canvas = document.createElement("canvas");
        canvas.width = Math.round(image.width * scale);
        canvas.height = Math.round(image.height * scale);
        canvas.getContext("2d").drawImage(image, 0, 0, canvas.width, canvas.height);
        resolve(canvas.toDataURL("image/jpeg", 0.82));
      };
      image.src = reader.result;
    };
    reader.readAsDataURL(file);
  });
}

async function addPhotos(files, eventId) {
  for (const file of [...files]) {
    try {
      state.photos.push({
        id: crypto.randomUUID(),
        eventId,
        name: file.name,
        dataUrl: await resizeImage(file),
        createdAt: new Date().toISOString()
      });
      saveState();
      if (pageName() === "program-detail") renderDetail();
      if (pageName() === "photos") renderPhotoArchive();
    } catch {
      alert(`这张照片暂时存不了：${file.name}`);
    }
  }
}

function downloadJson() {
  const blob = new Blob([JSON.stringify(state, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = "mdw-2026-personal-records.json";
  link.click();
  URL.revokeObjectURL(url);
}

function importJson(file) {
  const reader = new FileReader();
  reader.onload = () => {
    try {
      const imported = JSON.parse(reader.result);
      state = {
        checked: imported.checked || {},
        missed: imported.missed || {},
        reflections: imported.reflections || [],
        photos: imported.photos || []
      };
      saveState();
      init();
    } catch {
      alert("这个 JSON 不能导入，可能不是 MDW 记录文件。");
    }
  };
  reader.readAsText(file);
}

function bindSharedEvents() {
  document.body.addEventListener("click", async (event) => {
    const check = event.target.closest("[data-check]");
    if (check) {
      const id = check.dataset.check;
      state.checked[id] = !state.checked[id];
      if (state.checked[id]) state.missed[id] = false;
      saveState();
      if (pageName() === "program") renderProgramList();
      if (pageName() === "program-detail") renderDetail();
      if (pageName() === "itinerary") renderItinerary();
    }

    const missed = event.target.closest("[data-missed]");
    if (missed) {
      const id = missed.dataset.missed;
      state.missed[id] = !state.missed[id];
      if (state.missed[id]) state.checked[id] = false;
      saveState();
      if (pageName() === "program") renderProgramList();
      if (pageName() === "program-detail") renderDetail();
    }

    const deletePhoto = event.target.closest("[data-delete-photo]");
    if (deletePhoto) {
      state.photos = state.photos.filter((photo) => photo.id !== deletePhoto.dataset.deletePhoto);
      saveState();
      if (pageName() === "photos") renderPhotoArchive();
      if (pageName() === "program-detail") renderDetail();
    }

    const editThought = event.target.closest("[data-edit-thought]");
    if (editThought) {
      openThoughtForm(editThought.dataset.editThought);
    }

    const action = event.target.closest("[data-action]")?.dataset.action;
    if (action === "new-thoughts") openThoughtForm();
    if (action === "cancel-thoughts") closeThoughtForm();
    if (action === "copy-share") {
      const text = $("#share-summary").textContent;
      try {
        await navigator.clipboard.writeText(text);
      } catch {
        const area = document.createElement("textarea");
        area.value = text;
        document.body.appendChild(area);
        area.select();
        document.execCommand("copy");
        area.remove();
      }
    }
    if (action === "download-json") downloadJson();
    if (action === "reset-demo" && confirm("确定清空这个浏览器里的 MDW 记录吗？")) {
      state = { ...defaultState, checked: {}, missed: {}, reflections: [], photos: [] };
      saveState();
      init();
    }
  });

  $("#import-json")?.addEventListener("change", (event) => {
    const [file] = event.target.files;
    if (file) importJson(file);
  });
}

function bindPageEvents() {
  $("#program-search")?.addEventListener("input", renderProgramList);
  document.querySelectorAll(".segmented button").forEach((button) => {
    button.addEventListener("click", () => {
      document.querySelectorAll(".segmented button").forEach((item) => item.classList.toggle("active", item === button));
      renderProgramList();
    });
  });
  $("#detail-reflection-form")?.addEventListener("submit", addReflection);
  $("#detail-photo-input")?.addEventListener("change", (event) => addPhotos(event.target.files, event.target.dataset.programId));
  $("#archive-filter")?.addEventListener("change", (event) => {
    location.href = event.target.value === "all" ? "reflections.html" : `reflections.html?event=${event.target.value}`;
  });
  $("#photo-filter")?.addEventListener("change", (event) => {
    location.href = event.target.value === "all" ? "photos.html" : `photos.html?event=${event.target.value}`;
  });
}

function init() {
  setActiveNav();
  renderStats();
  if (pageName() === "index") renderHome();
  if (pageName() === "itinerary") renderItinerary();
  if (pageName() === "program") renderProgramList();
  if (pageName() === "program-detail") renderDetail();
  if (pageName() === "reflections") renderArchive();
  if (pageName() === "photos") renderPhotoArchive();
  if (pageName() === "share") renderShare();
  if (pageName() === "data") renderShare();
}

bindSharedEvents();
bindPageEvents();
init();
